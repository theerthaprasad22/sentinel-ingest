@router.get("/state")
def sandbox_state() -> dict:
    d = asdict(state)
    d["defences_on"] = [
        k for k in ("fingerprint_check", "rate_limit", "captcha_wall",
                    "hard_block", "silent_empty")
        if getattr(state, k)
    ]
    return d


@router.post("/control")
async def sandbox_control(req: Request) -> dict:
    """Toggle defences. Body: {"fingerprint_check": true, "markup_version": 3}"""
    try:
        payload = await req.json()
    except (json.JSONDecodeError, ValueError):
        payload = {}
    changed = {}
    for key, value in (payload or {}).items():
        if not hasattr(state, key) or key in ("hits", "blocked"):
            continue
        current = getattr(state, key)
        cast = type(current)(value) if not isinstance(current, bool) else bool(value)
        setattr(state, key, cast)
        changed[key] = cast
    if payload.get("reset"):
        fresh = SandboxState()
        for f in fresh.__dataclass_fields__:
            setattr(state, f, getattr(fresh, f))
        _window.clear()
        changed = {"reset": True}
    return {"ok": True, "changed": changed, "state": asdict(state)}
